import {test,expect} from '@playwright/test';

test('real browser physics, both policies, pause, reset, presets and free throws',async({page})=>{
  const errors=[],outsideRequests=[],modelRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',req=>{if(req.url().endsWith('.onnx'))modelRequests.push(req.url());if(!req.url().startsWith(new URL(test.info().project.use.baseURL).origin)&&!req.url().startsWith('blob:')&&!req.url().startsWith('data:'))outsideRequests.push(req.url());});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/?task=dynamic-dex');
  await expect(page.locator('#throw')).toBeEnabled({timeout:60000});
  await expect(page.locator('#error')).toBeHidden();
  await page.screenshot({path:'/tmp/catch-lab-desktop.png',fullPage:true});
  await page.locator('#throw').click();
  await page.waitForFunction(()=>window.catchLab.state.time>=.8);
  await page.locator('#throw').click();
  await page.waitForTimeout(250);
  const paused=await page.evaluate(()=>window.catchLab.state.time);
  await page.waitForTimeout(300);
  expect(await page.evaluate(()=>window.catchLab.state.time)).toBe(paused);
  expect(await page.evaluate(()=>window.catchLab.state.rootHeight)).toBeGreaterThan(.5);
  await expect(page.locator('#level')).toBeDisabled();
  await page.locator('#reset').click();
  await expect(page.locator('#level')).toBeEnabled();
  await expect(page.locator('#sim-time')).toHaveText('0.00');
  await page.locator('#level').selectOption('custom');
  await page.locator('[data-preset="wide"]').click();
  await page.locator('[data-preset="easy"]').click();
  await page.locator('#policy').selectOption('alternate');
  await expect(page.locator('#throw')).toBeEnabled();
  await page.locator('#throw').click();
  await page.waitForFunction(()=>window.catchLab.state.done,{timeout:90000});
  const result=await page.evaluate(()=>window.catchLab.state);
  expect(result.frames).toBeGreaterThan(30);
  if(result.success)expect(result.continuousHold).toBeGreaterThan(2);
  expect(result.rootHeight).toBeGreaterThan(.4);
  expect(result.finiteObservation).toBe(true);
  await expect(page.locator('#error')).toBeHidden();
  await page.screenshot({path:'/tmp/catch-lab-complete.png',fullPage:true});
  await page.locator('#reset').click();
  await page.locator('[data-mode="free"]').click();
  await expect(page.locator('#free-settings')).toBeVisible();
  await page.locator('#vx').fill('-4');
  await page.locator('#throw').click();
  await page.waitForFunction(()=>window.catchLab.state.time>.7);
  await page.locator('#reset').click();
  await page.locator('[data-camera="hands"]').click();
  await page.locator('#about-button').click();
  await expect(page.locator('#about')).toBeVisible();
  await page.keyboard.press('Escape');
  expect(errors).toEqual([]);
  expect(outsideRequests).toEqual([]);
  expect(modelRequests).toHaveLength(1);
  expect(modelRequests[0]).toContain('/assets/controller.onnx');
  await expect(page.locator('body')).not.toContainText(/checkpoint|locomotion|hierarch/i);
});

test('mobile layout stays within the screen and controls remain usable',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/?task=dynamic-dex');
  await expect(page.locator('#throw')).toBeEnabled({timeout:60000});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.locator('#sample').click();
  await expect(page.locator('#error')).toBeHidden();
  await expect(page.getByRole('link',{name:'All tasks'})).toBeVisible();
  await page.screenshot({path:'/tmp/catch-lab-mobile.png',fullPage:true});
});
